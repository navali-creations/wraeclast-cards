import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const rootDirectory = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const packageJsonPath = resolve(rootDirectory, "package.json");
const outputPath = resolve(
  rootDirectory,
  "src/lib/divinationCardsVersion.generated.ts",
);
const packageMetadata = JSON.parse(await readFile(packageJsonPath, "utf8"));
const version = packageMetadata.dependencies?.["@navali/poe1-divination-cards"];

if (typeof version !== "string" || !/^\d+\.\d+\.\d+$/.test(version)) {
  throw new Error("@navali/poe1-divination-cards must use an exact version");
}

const contents = `// Generated by scripts/generate-divination-card-version.mjs.\nexport const POE1_DIVINATION_CARDS_VERSION = ${JSON.stringify(version)};\n`;

let existingContents;
try {
  existingContents = await readFile(outputPath, "utf8");
} catch (error) {
  if (error.code !== "ENOENT") throw error;
}

if (existingContents !== contents) {
  await writeFile(outputPath, contents);
}
